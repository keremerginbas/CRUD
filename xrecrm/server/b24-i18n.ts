const PIECE_SPLIT = /([<>"]|(?<!\\)')/;
const LITERAL = /'((?:[^'\\\n]|\\.)*)'|"((?:[^"\\\n]|\\.)*)"/g;

function translatePiece(piece: string, dict: Record<string, string>): string {
  const core = piece.trim();
  if (!core) return piece;
  const hit = dict[core];
  if (hit === undefined) return piece;
  const lead = piece.slice(0, piece.indexOf(core));
  const trail = piece.slice(piece.indexOf(core) + core.length);
  return lead + hit + trail;
}
const translateText = (text: string, dict: Record<string, string>) =>
  text
    .split(PIECE_SPLIT)
    .map((p) => (p.length > 1 || !/[<>"']/.test(p) ? translatePiece(p, dict) : p))
    .join("");

/** Panel HTML'ini istenen dile çevirir (Türkçe ise dokunmaz). */
export function localizeHtml(html: string, lang: Lang, dict: Record<string, string> = PANEL_EN): string {
  if (lang === "tr") return html;
  const start = html.indexOf("<script>");
  const end = html.lastIndexOf("</script>");
  const head = start < 0 ? html : html.slice(0, start);
  const script = start < 0 ? "" : html.slice(start, end);
  const tail = start < 0 ? "" : html.slice(end);
  // Stil bloğu çevrilmez; yalnız gövde metinleri ve öznitelikler.
  const styleEnd = head.indexOf("</style>");
  const pre = styleEnd < 0 ? "" : head.slice(0, styleEnd);
  const body = styleEnd < 0 ? head : head.slice(styleEnd);
  const outBody = body
    .replace(/>([^<>]+)</g, (_m, t: string) => `>${translatePiece(t, dict)}<`)
    .replace(/\b(placeholder|title|aria-label)="([^"]*)"/g, (_m, a: string, v: string) => `${a}="${translatePiece(v, dict)}"`);
  const outScript = script.replace(LITERAL, (m: string, single?: string, double?: string) => {
    const q = m[0];
    const content = single ?? double ?? "";
    return q + translateText(content, dict) + q;
  });
  return (pre + outBody + outScript + tail).replace('<html lang="tr">', '<html lang="en">');
}

